"""Reproducible exploratory novelty fit or independently labeled supervised research."""
import argparse
import csv
import importlib.metadata
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from vantage.imagery import sha256_file,stable_hash,atomic_json
from vantage.ml import build_features,publish_label_template,novelty_experiment,supervised_experiment


def run(datasets,out,mode="novelty",labels=None):
    label_rows=[]
    if labels:
        if Path(labels).suffix.lower()!=".csv":raise ValueError("Independent labels must be a CSV file")
        with Path(labels).open(encoding="utf-8-sig",newline="") as stream:
            label_rows=list(csv.DictReader(stream))
    rows=[];lineage=[];targets=set()
    for directory in datasets:
        path=Path(directory)
        manifest=json.loads((path/"manifest.json").read_text(encoding="utf-8"))
        if stable_hash(manifest["recipe"])[:20]!=manifest["dataset_id"]:
            raise ValueError("Dataset recipe identifier mismatch")
        source=json.loads((path/"source-observations.json").read_text(encoding="utf-8"))
        if sha256_file(path/"source-observations.json")!=manifest["recipe"]["source_sha256"]:
            raise ValueError("Archived observations checksum mismatch")
        if sha256_file(path/"observations.jsonl")!=manifest["observations_sha256"]:
            raise ValueError("Feature-source observations checksum mismatch")
        observations=[json.loads(line) for line in (path/"observations.jsonl").read_text(encoding="utf-8").splitlines()]
        features=build_features(manifest,observations,source["rainfall"])
        rows.extend(features);targets.add(manifest["target_year"])
        lineage.append(dict(dataset_id=manifest["dataset_id"],manifest_sha256=sha256_file(path/"manifest.json"),observations_sha256=sha256_file(path/"observations.jsonl")))
    if len(targets)!=1 or len({r["sample_id"] for r in rows})!=len(rows):
        raise ValueError("Datasets must have a common target year and unique samples")
    out=Path(out);out.mkdir(parents=True,exist_ok=True)
    (out/"features.jsonl").write_text("".join(json.dumps(r,allow_nan=False)+"\n" for r in rows),encoding="utf-8")
    template_note=publish_label_template(rows,out/"labels-template.csv",ROOT/"web/data/labels-template.csv")
    # Only features and a blank labeling template are exposed by the local desk.
    # Independent outcome records are never copied into the web directory.
    (ROOT/"web/data/features.jsonl").write_bytes((out/"features.jsonl").read_bytes())
    report,model=novelty_experiment(rows,next(iter(targets))) if mode=="novelty" else supervised_experiment(rows,label_rows)
    report["label_template_note"]=template_note
    recipe=dict(mode=mode,datasets=lineage,features_sha256=sha256_file(out/"features.jsonl"),
        labels_sha256=sha256_file(labels) if labels else None,code_hashes={"ml":sha256_file(ROOT/"vantage/ml.py"),"runner":sha256_file(__file__)},seed=42,
        software={x:importlib.metadata.version(x) for x in ("numpy","scikit-learn","joblib")})
    report.update(run_id=stable_hash(recipe)[:20],lineage=recipe,
        software={x:importlib.metadata.version(x) for x in ("numpy","scikit-learn","joblib")})
    run_path=out/report["run_id"];run_path.mkdir(exist_ok=True)
    if model is not None:
        import joblib
        joblib.dump(model,run_path/"model.joblib")
        report["model_sha256"]=sha256_file(run_path/"model.joblib")
    (run_path/"report.json").write_text(json.dumps(report,indent=2,allow_nan=False),encoding="utf-8")
    (run_path/"model-card.md").write_text(f'# Vantage {report["mode"]}\n\nStatus: {report["status"]}.\n\n{report["limitation"]}\n\nInputs, versions, split, seed and artifact hashes are in report.json. Only load model.joblib generated by this trusted local pipeline; pickle-based model files are executable artifacts. No operational or commercial performance is validated.\n',encoding="utf-8")
    if mode=="novelty":
        atomic_json(ROOT/"web/data/ml.json",report)
    else:
        atomic_json(ROOT/"web/data/supervised-status.json",report)
    print(json.dumps(dict(status=report["status"],run_id=report["run_id"],model_trained=report["model_trained"])),flush=True)
    return report


if __name__=="__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--dataset",type=Path,nargs="+")
    p.add_argument("--out",type=Path,default=ROOT/"outputs/ml/experiments")
    p.add_argument("--mode",choices=["novelty","supervised"],default="novelty")
    p.add_argument("--labels",type=Path)
    a=p.parse_args()
    if not a.dataset:
        latest=json.loads((ROOT/"outputs/ml/datasets/latest.json").read_text())
        a.dataset=[ROOT/"outputs/ml/datasets"/latest["path"]]
    try:run(a.dataset,a.out,a.mode,a.labels)
    except (ValueError,KeyError,OSError) as exc:p.error(str(exc))
